// ============================================================================
// Полифил IndexedDB для Node.js-окружения (unit-тесты)
// ============================================================================
//
// Dexie работает поверх браузерного API IndexedDB, которого в Node.js нет.
// `fake-indexeddb/auto` — это side-effect импорт, который глобально
// подменяет объект `indexedDB` на совместимую in-memory реализацию.
//
// Ключевое: импорт выполняется один раз при старте vitest (до любых тестов),
// поэтому в самих тестовых файлах ничего импортировать не нужно — Dexie
// просто «видит» полифил через глобальную переменную.
//
// Альтернативы (почему выбран именно этот подход):
//   - fake-indexeddb без /auto: нужно вручную создавать экземпляр и
//     внедрять его в глобальную область, /auto делает это автоматически.
//   - indexeddb-shim: устарел, не поддерживает современные фичи.
//   - jsdom environment: jsdom в vitest тоже можно заставить работать,
//     но fake-indexeddb легче и быстрее.
// ============================================================================
import 'fake-indexeddb/auto'
